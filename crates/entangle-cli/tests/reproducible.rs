//! ATC-PKG-1..4: reproducible packaging, cross-host workflow, lockfile
//! requirement, provenance and rebuild verification.
//!
//! These compile the real `examples/hello-world` plugin to wasm, so they need
//! the `wasm32-wasip2` target (installed in the CI `test` job) and a reachable
//! registry or a warm cargo cache. The builds are serialised by a process-wide
//! lock: each is ~150 MB of target directory and one core-minute.
//!
//! Each build runs from a **separate copy** of the project in a fresh temp dir
//! with its own `CARGO_TARGET_DIR`, so the absolute project path, the target
//! path and the temp locations all differ between builds. Byte-identical
//! output therefore proves path remapping, not just cache reuse.

#![cfg(unix)]

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use assert_cmd::Command;
use predicates::prelude::*;
use tempfile::TempDir;

static BUILD_LOCK: Mutex<()> = Mutex::new(());

fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .unwrap()
        .to_path_buf()
}

fn key() -> PathBuf {
    repo_root().join("tests/fixtures/repro-ci-key.pem")
}

/// `entangle` with an isolated `$HOME` but the real cargo / rustup homes, so
/// the toolchain and the registry cache keep working.
fn entangle(home: &Path) -> Command {
    let real_home = std::env::var_os("HOME").map(PathBuf::from);
    let mut c = Command::cargo_bin("entangle").unwrap();
    c.env("HOME", home);
    if std::env::var_os("CARGO_HOME").is_none() {
        if let Some(h) = &real_home {
            c.env("CARGO_HOME", h.join(".cargo"));
        }
    }
    if std::env::var_os("RUSTUP_HOME").is_none() {
        if let Some(h) = &real_home {
            c.env("RUSTUP_HOME", h.join(".rustup"));
        }
    }
    c.env_remove("SOURCE_DATE_EPOCH");
    c
}

fn copy_dir(src: &Path, dst: &Path) {
    std::fs::create_dir_all(dst).unwrap();
    for e in std::fs::read_dir(src).unwrap() {
        let e = e.unwrap();
        let name = e.file_name();
        if name == "target" || name == "dist" {
            continue;
        }
        let (from, to) = (e.path(), dst.join(&name));
        if e.file_type().unwrap().is_dir() {
            copy_dir(&from, &to);
        } else {
            std::fs::copy(&from, &to).unwrap();
        }
    }
}

/// A private copy of hello-world whose SDK path dependency is absolute.
fn hello_copy(parent: &Path) -> PathBuf {
    let dst = parent.join("hello-world");
    copy_dir(&repo_root().join("examples/hello-world"), &dst);
    let manifest = dst.join("Cargo.toml");
    let text = std::fs::read_to_string(&manifest).unwrap();
    let sdk = repo_root().join("crates/entangle-sdk");
    let text = text.replace("../../crates/entangle-sdk", &sdk.display().to_string());
    std::fs::write(&manifest, text).unwrap();
    dst
}

/// Public key (hex) of the fixture signing key.
fn fixture_public_key_hex() -> String {
    let pem = std::fs::read_to_string(key()).unwrap();
    let kp = entangle_signing::IdentityKeyPair::from_pem(&pem).unwrap();
    hex::encode(kp.public().as_bytes())
}

/// Trust the fixture key as a plugin publisher in `home`'s keyring.
fn trust_fixture_key(home: &Path) {
    entangle(home)
        .args([
            "keyring",
            "add",
            &fixture_public_key_hex(),
            "--name",
            "repro-ci",
        ])
        .assert()
        .success();
}

/// A dependency-free `cdylib` plugin `tiny` at `parent/<dir_name>`, with a
/// committed `Cargo.lock` and an optional build script. It needs neither the
/// SDK nor a registry, and compiles for wasm32-wasip2 in seconds, so it can
/// exercise the build and rebuild paths cheaply.
fn tiny_plugin(parent: &Path, dir_name: &str, build_rs: Option<&str>, lib_rs: &str) -> PathBuf {
    let dir = parent.join(dir_name);
    std::fs::create_dir_all(dir.join("src")).unwrap();
    std::fs::write(
        dir.join("Cargo.toml"),
        "[workspace]\n\n[package]\nname = \"tiny\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\
         publish = false\n\n[lib]\ncrate-type = [\"cdylib\"]\n\n[profile.release]\nopt-level = \"s\"\n",
    )
    .unwrap();
    std::fs::write(
        dir.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n\
         version = 4\n\n[[package]]\nname = \"tiny\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    let manifest = std::fs::read_to_string(repo_root().join("examples/hello-world/entangle.toml"))
        .unwrap()
        .replace("hello-world@0.1.0", "tiny@0.1.0");
    std::fs::write(dir.join("entangle.toml"), manifest).unwrap();
    if let Some(b) = build_rs {
        std::fs::write(dir.join("build.rs"), b).unwrap();
    }
    std::fs::write(dir.join("src/lib.rs"), lib_rs).unwrap();
    dir
}

const TINY_LIB: &str =
    "#[no_mangle]\npub extern \"C\" fn tiny(x: u32) -> u32 { x.wrapping_mul(3) }\n";

/// `plugins build <project>` of a tiny plugin with its default target and
/// output directories; returns the archive path.
fn build_tiny(home: &Path, project: &Path) -> PathBuf {
    entangle(home)
        .env_remove("CARGO_TARGET_DIR")
        .args(["plugins", "build"])
        .arg(project)
        .arg("--key")
        .arg(key())
        .assert()
        .success();
    let archive = project.join("dist/tiny-0.1.0.tar.zst");
    assert!(archive.is_file(), "no archive at {}", archive.display());
    archive
}

fn verify_rebuild(home: &Path, package: &Path, source: &Path) -> assert_cmd::assert::Assert {
    entangle(home)
        .env_remove("CARGO_TARGET_DIR")
        .args(["plugins", "verify", "--rebuild"])
        .arg(package)
        .arg("--source")
        .arg(source)
        .assert()
}

struct Built {
    _root: TempDir,
    project: PathBuf,
    out: PathBuf,
    archive: PathBuf,
}

fn build_hello(home: &Path) -> Built {
    let _g = BUILD_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let root = TempDir::new().unwrap();
    let project = hello_copy(root.path());
    let out = root.path().join("out");
    entangle(home)
        .env("CARGO_TARGET_DIR", root.path().join("target"))
        .args(["plugins", "build"])
        .arg(&project)
        .arg("--key")
        .arg(key())
        .arg("--out")
        .arg(&out)
        .assert()
        .success();
    let archive = out.join("hello-world-0.1.0.tar.zst");
    assert!(archive.is_file(), "no archive in {}", out.display());
    Built {
        _root: root,
        project,
        out,
        archive,
    }
}

