/// Code a build script generates into `OUT_DIR` and `include!`s carries its
/// absolute `$TARGET/.../out/*.rs` path into panic locations. The target
/// directory must be remapped like the project, or the rebuild (which uses a
/// scratch target dir) never reproduces such a plugin, and a target dir
/// outside the project leaks into the wasm.
#[test]
fn build_script_out_dir_paths_are_remapped_and_rebuild_verifies() {
    const BUILD_RS: &str = r#"fn main() {
    let out = std::env::var("OUT_DIR").unwrap();
    std::fs::write(
        format!("{out}/gen.rs"),
        "pub fn gen(x: Option<u32>) -> u32 { x.expect(\"generated code\") }\n",
    )
    .unwrap();
}
"#;
    const LIB_RS: &str = "include!(concat!(env!(\"OUT_DIR\"), \"/gen.rs\"));\n\
        #[no_mangle]\npub extern \"C\" fn tiny(x: u32) -> u32 { gen(if x == 0 { None } else { Some(x) }) }\n";
    let home = TempDir::new().unwrap();
    trust_fixture_key(home.path());
    let root = TempDir::new().unwrap();
    let project = tiny_plugin(root.path(), "tiny", Some(BUILD_RS), LIB_RS);

    let archive = build_tiny(home.path(), &project);
    let wasm = std::fs::read(project.join("dist/plugin.wasm")).unwrap();
    assert!(
        wasm.windows(6).any(|w| w == b"gen.rs"),
        "fixture must embed the generated file's path"
    );
    verify_rebuild(home.path(), &archive, &project)
        .success()
        .stdout(predicate::str::contains("PASS"));

    // A target directory outside the project does not leak either.
    let target = root.path().join("elsewhere-target");
    entangle(home.path())
        .env("CARGO_TARGET_DIR", &target)
        .args(["plugins", "build"])
        .arg(&project)
        .arg("--key")
        .arg(key())
        .arg("--out")
        .arg(root.path().join("out2"))
        .assert()
        .success();
    let wasm2 = std::fs::read(root.path().join("out2/plugin.wasm")).unwrap();
    let needle = target.display().to_string();
    assert!(
        !wasm2.windows(needle.len()).any(|w| w == needle.as_bytes()),
        "wasm embeds the target directory {needle}"
    );
    assert_eq!(wasm, wasm2, "target directory location changed the wasm");
}

/// The rebuild runs with the recorded `SOURCE_DATE_EPOCH`, not the
/// verifier's: a plugin whose build embeds the epoch reproduces from a shell
/// without the variable. A signature bundle whose `created_at` is not the
/// recorded epoch is not what the reproducible build produced.
#[test]
fn rebuild_uses_the_recorded_source_date_epoch() {
    const BUILD_RS: &str = r#"fn main() {
    println!("cargo:rerun-if-env-changed=SOURCE_DATE_EPOCH");
    let epoch = std::env::var("SOURCE_DATE_EPOCH").unwrap_or_default();
    println!("cargo:rustc-env=TINY_EPOCH={epoch}");
}
"#;
    const LIB_RS: &str = "#[no_mangle]\npub static TINY_EPOCH: [u8; 10] = {\n\
        let s = env!(\"TINY_EPOCH\").as_bytes();\n    let mut a = [0u8; 10];\n    let mut i = 0;\n\
        while i < s.len() && i < 10 { a[i] = s[i]; i += 1; }\n    a\n};\n";
    let home = TempDir::new().unwrap();
    trust_fixture_key(home.path());
    let root = TempDir::new().unwrap();
    let project = tiny_plugin(root.path(), "tiny", Some(BUILD_RS), LIB_RS);
    entangle(home.path())
        .env("SOURCE_DATE_EPOCH", "1700000000")
        .env_remove("CARGO_TARGET_DIR")
        .args(["plugins", "build"])
        .arg(&project)
        .arg("--key")
        .arg(key())
        .assert()
        .success();
    let archive = project.join("dist/tiny-0.1.0.tar.zst");
    let wasm = std::fs::read(project.join("dist/plugin.wasm")).unwrap();
    assert!(
        wasm.windows(10).any(|w| w == b"1700000000"),
        "fixture must embed the epoch"
    );

    // `entangle()` clears SOURCE_DATE_EPOCH: the verifier's env differs.
    verify_rebuild(home.path(), &archive, &project)
        .success()
        .stdout(predicate::str::contains("PASS"));

    let resigned = repack_with(&archive, |f| {
        let text = String::from_utf8(f.signature.clone()).unwrap();
        assert!(text.contains("created_at = 1700000000"), "{text}");
        f.signature = text
            .replace("created_at = 1700000000", "created_at = 1700000001")
            .into_bytes();
    });
    verify_rebuild(home.path(), &resigned, &project)
        .failure()
        .stdout(predicate::str::contains("FAIL: "))
        .stdout(predicate::str::contains("created_at"));
}

/// The source digest covers the source, not the builder's own earlier
/// outputs: repeated builds into an output directory inside the project (any
/// name, not just `dist`) give the same archive.
#[test]
fn outputs_inside_the_project_do_not_change_the_source_digest() {
    let home = TempDir::new().unwrap();
    let root = TempDir::new().unwrap();
    let project = tiny_plugin(root.path(), "tiny", None, TINY_LIB);
    let wasm = root.path().join("prebuilt.wasm");
    std::fs::write(&wasm, b"\0asm\x01\0\0\0").unwrap();
    let build = |out: Option<&Path>| -> (Vec<u8>, String) {
        let mut c = entangle(home.path());
        c.args(["plugins", "build"])
            .arg(&project)
            .arg("--key")
            .arg(key())
            .arg("--wasm")
            .arg(&wasm);
        if let Some(o) = out {
            c.arg("--out").arg(o);
        }
        c.assert().success();
        let dir = out.map(Path::to_path_buf).unwrap_or(project.join("dist"));
        let archive = std::fs::read(dir.join("tiny-0.1.0.tar.zst")).unwrap();
        let prov: serde_json::Value =
            serde_json::from_slice(&std::fs::read(dir.join("provenance.json")).unwrap()).unwrap();
        (archive, prov["source_digest"].as_str().unwrap().to_owned())
    };
    let out = project.join("out");
    let (a1, d1) = build(Some(&out));
    let (a2, d2) = build(Some(&out));
    let (a3, d3) = build(Some(&out));
    assert_eq!(d1, d2, "second build hashed the first build's outputs");
    assert_eq!(d2, d3);
    assert_eq!(a1, a2);
    assert_eq!(a2, a3);
    let (_, d4) = build(None);
    assert_eq!(d1, d4, "default build hashed the --out directory");
}

/// `--rebuild` is a superset of the plain signature check: a package whose
/// signature cannot be checked (publisher not trusted) or does not verify is
/// a `FAIL: <first difference>`, never a PASS or a bare error.
#[test]
fn rebuild_verify_requires_a_valid_publisher_signature() {
    let home = TempDir::new().unwrap();
    let root = TempDir::new().unwrap();
    let project = tiny_plugin(root.path(), "tiny", None, TINY_LIB);
    let archive = build_tiny(home.path(), &project);

    // Untrusted publisher (no keyring at all): the signature is unchecked.
    verify_rebuild(home.path(), &archive, &project)
        .failure()
        .stdout(predicate::str::contains("PASS").not())
        .stdout(predicate::str::contains("FAIL: "))
        .stdout(predicate::str::contains("not in the keyring"));

    // Trusted publisher, signature bytes corrupted (hashes still match).
    trust_fixture_key(home.path());
    let forged = repack_with(&archive, |f| {
        let mut v: toml::Value =
            toml::from_str(std::str::from_utf8(&f.signature).unwrap()).unwrap();
        let sig = v["signature"].as_str().unwrap().to_owned();
        let flipped = if sig.starts_with('0') { "1" } else { "0" };
        v["signature"] = toml::Value::String(format!("{flipped}{}", &sig[1..]));
        f.signature = toml::to_string(&v).unwrap().into_bytes();
    });
    verify_rebuild(home.path(), &forged, &project)
        .failure()
        .stdout(predicate::str::contains("PASS").not())
        .stdout(predicate::str::contains("FAIL: signature does not verify"));

    // And the genuine package passes once the publisher is trusted.
    verify_rebuild(home.path(), &archive, &project)
        .success()
        .stdout(predicate::str::contains("publisher signature verified"));
}

